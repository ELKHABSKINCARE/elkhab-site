function ebInciOpen(productId){
  const d = INCI_DETAILS[productId];
  if(!d) return;

  let html = '<div class="eb-inci-eyebrow">Composition</div>';
  html += '<div class="eb-inci-title">'+d.title+'</div>';

  if(d.parts){
    d.parts.forEach(function(part){
      html += '<div class="eb-inci-section"><h4>'+part.label+'</h4>';
      html += '<p class="eb-inci-list">'+part.ingredients+'</p>';
      html += '<div class="eb-inci-legend">';
      part.legend.forEach(function(l){ html += l+'<br>'; });
      html += '</div>';
      if(part.natural || part.organic){
        html += '<div class="eb-inci-stats" style="margin-top:14px">';
        if(part.natural){ html += '<div><div class="eb-inci-stat-value">'+part.natural+'%</div><div class="eb-inci-stat-label">Origine naturelle</div></div>'; }
        if(part.organic){ html += '<div><div class="eb-inci-stat-value">'+part.organic+'%</div><div class="eb-inci-stat-label">Agriculture biologique</div></div>'; }
        html += '</div>';
      }
      html += '</div>';
    });
  } else {
    html += '<div class="eb-inci-section"><h4>Liste des ingrédients (INCI)</h4><p class="eb-inci-list">'+d.ingredients+'</p>';
    html += '<div class="eb-inci-legend">';
    d.legend.forEach(function(l){ html += l+'<br>'; });
    html += '</div></div>';

    if(d.natural || d.organic){
      html += '<div class="eb-inci-section"><h4>Origine</h4><div class="eb-inci-stats">';
      if(d.natural){ html += '<div><div class="eb-inci-stat-value">'+d.natural+'%</div><div class="eb-inci-stat-label">Ingrédients d\'origine naturelle</div></div>'; }
      if(d.organic){ html += '<div><div class="eb-inci-stat-value">'+d.organic+'%</div><div class="eb-inci-stat-label">Issus de l\'agriculture biologique</div></div>'; }
      html += '</div></div>';
    }
  }

  html += '<div class="eb-inci-section"><h4>Engagement</h4><p>'+d.engagement+'</p></div>';

  if(d.certification){
    html += '<div class="eb-inci-section"><h4>Certification</h4><div class="eb-inci-cert">'+d.certification+'</div></div>';
  }

  document.getElementById('ebInciContent').innerHTML = html;
  document.getElementById('ebInciOverlay').classList.add('open');
}
function ebInciClose(){
  document.getElementById('ebInciOverlay').classList.remove('open');
}

window.ebInciOpen = ebInciOpen;
window.ebInciClose = ebInciClose;
